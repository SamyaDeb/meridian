// Generates docs/outputs/BENCHMARKS.md from bench/out/* and the Foundry gas bench (BENCHMARKS_PLAN B1–B9).
//   cd contracts && forge test --match-contract RealEngineGasBench   # writes contracts/bench-out/real_engine_gas.csv
//   cd bench && pnpm report
// Runnable any time: missing runs become explicit placeholders. PRD §7.1: numbers carry network, block range, commit,
// date; files labelled anvil-* (bench/src/stats.ts networkLabel) are shown as local-only, never as testnet evidence.
import { execSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { type Csv, parseCsv, provenance, renderB7, renderGasTable } from "./src/report.js";

const HERE = fileURLToPath(new URL(".", import.meta.url));
const OUT = `${HERE}out/`;
const DOC = `${HERE}../docs/outputs/BENCHMARKS.md`;
const FOUNDRY = `${HERE}../contracts/bench-out/real_engine_gas.csv`;
const read = (p: string): Csv | null => (existsSync(p) ? parseCsv(readFileSync(p, "utf8")) : null);
const commit = execSync("git rev-parse --short HEAD", { cwd: HERE }).toString().trim();
const today = new Date().toISOString().slice(0, 10);
const files = existsSync(OUT) ? readdirSync(OUT) : [];

const foundry = read(FOUNDRY);
// CSVs written before the gasEstimate/touchAllowance columns (P7): the allowance their limits include, from
// bench/gas_onchain.ts at the commit in the file (064f327: TOUCH_ALLOWANCE_GAS default 70000 on live chains; 1e202d5: none).
const LEGACY_TOUCH: Record<string, number> = { "gas_onchain_10143_2026-10-06.csv": 70_000 };
// oldest run first (by its first block: file names of two runs on the same UTC day don't sort chronologically)
const firstBlock = (f: string): number => Number(parseCsv(readFileSync(`${OUT}${f}`, "utf8"))[0]?.block ?? 0);
const gasFiles = files.filter((f) => /^gas_onchain_\d+_.*\.csv$/.test(f)).sort((a, b) => firstBlock(a) - firstBlock(b));
const anvilGas = files.filter((f) => /^gas_onchain_anvil-/.test(f));
const loadFiles = files.filter((f) => /^load_\d+_.*\.json$/.test(f));
const anvilLoad = files.filter((f) => /^load_anvil-/.test(f));
const b7 = read(`${OUT}b7_liquidation_latency.csv`);
const tau = read(`${OUT}sqrt_tau.csv`);

const s: string[] = [];
s.push("# BENCHMARKS: why only Monad, with numbers (generated)");
s.push("");
s.push(`Generated by \`bench/report.ts\` on ${today} at commit \`${commit}\`. Regenerate: \`cd contracts && forge test --match-contract RealEngineGasBench && cd ../bench && pnpm report\`.`);
s.push("Rules (PRD §7.1, BENCHMARKS_PLAN): every number names its network, block range, commit and date; anvil runs use the Ethereum gas schedule and a local clock and are never presented as testnet/mainnet evidence. **Monad bills the gas limit and its receipts report `gasUsed` = the limit** (checked 30 Sep with receipts and `debug_traceTransaction`), so the testnet column is what a user pays; `eth_estimateGas` (≈ limit / 1.2) is the only view of execution gas.");
s.push("");
s.push("## B1 / B2: gas per operation");
if (gasFiles.length === 0) {
  s.push("_No testnet/mainnet receipts yet (`pnpm gas` against 10143/143)._");
} else {
  for (const f of gasFiles) {
    const rows = parseCsv(readFileSync(`${OUT}${f}`, "utf8"));
    const network = f.split("_")[2]!;
    s.push(`Source: \`bench/out/${f}\` — network ${network}, ${provenance(rows)}. Foundry column: \`contracts/bench-out/real_engine_gas.csv\`${foundry ? "" : " (**missing**: run the Foundry bench)"}.`);
    s.push("");
    s.push(renderGasTable({ foundry, onchain: rows, network, ...(LEGACY_TOUCH[f] !== undefined ? { legacyTouchAllowance: LEGACY_TOUCH[f] } : {}) }));
    if (LEGACY_TOUCH[f] !== undefined) s.push(`\n_This file predates the \`gasEstimate\` column: its limits were built as ⌈estimate × 1.2⌉ + ${LEGACY_TOUCH[f].toLocaleString("en-US")} (\`bench/gas_onchain.ts\` at its commit), so the estimate is derived as (limit − allowance) / 1.2._`);
    s.push("");
  }
  s.push("Reading: the < 100k place + cancel target is met on the Foundry (Cancun) schedule. On Monad testnet `eth_estimateGas` for the same ops is ≈ 3.2× higher (MIP-8 charges 8,100 per cold storage page read), and Monad bills the **limit**, not the gas used: ⌈estimate × 1.2⌉ plus, since 5 Oct, a 70,000 `TOUCH_ALLOWANCE_GAS` on every tx (a `latest` estimate misses the block's first funding touch; without it a `replaceOrder` ran out of gas on 5 Oct). The per-market funding touch is O(1) and flat in the number of positions (`test/unit/ClearingHouseGas.t.sol`).");
  s.push("");
  s.push("**Found #19 (6 Oct receipts up vs 30 Sep), settled:** the 6 Oct limits carry the 70,000 allowance and the 30 Sep ones don't (`bench/gas_onchain.ts` at `064f327` vs `1e202d5`). With it taken out, the 6 Oct execution estimates are +0.2% (cancel) to +5% (match) over 30 Sep (P2/P3 code growth and book state), not +40–50%. The 7 Oct (IST) rerun records `eth_estimateGas` next to every receipt and reproduces the derived 6 Oct estimates within 0.2% for place, cancel, replace, close and funding (match 197,228 vs 246,285: the fill's cost depends on the resting maker's state); every receipt's `gasUsed` equals ⌈estimate × 1.2⌉ + 70,000. Lowering the billed cost means a smaller allowance: only the first tx in a block pays the touch, so a bot that knows it is not first (or estimates on `pending`, RUNBOOK §1 > VERIFY) can drop it.");
  s.push("");
  s.push("5 Oct rerun (decision D12): aborted after 18 receipts, not used in the table above. The testnet endpoint was a free tier (BLOCKED #5) and the bench wallet ran out of MON; a `replaceOrder` at ⌈estimate × 1.2⌉ ran out of gas (the `latest` estimate misses the block's first funding touch), so `gasLimitFor` now adds `TOUCH_ALLOWANCE_GAS` (70,000 on live chains). Rebuilt read-only: `bench/out/partial_gas_onchain_10143_2026-10-05.csv`.");
}
if (foundry) {
  const f = new Map(foundry.map((r) => [r.op, r]));
  const g = (k: string) => (f.get(k) ? Number(f.get(k)!.gas).toLocaleString("en-US") : "—");
  s.push("");
  s.push("**B2 funding update (Foundry, Cancun schedule, local; commit " + commit + "):** CH-own first-touch incremental " + g("funding_ch_own_incremental") + " (target < 30,000) · checkpoint block " + g("funding_ch_own_checkpoint_incremental") + " (< 40,000) · later touch in the same tx " + g("funding_later_touch_same_tx") + " (< 3,000) · whole first-touch tx " + g("funding_first_touch_tx") + ".");
}
if (anvilGas.length) s.push(`\nLocal-only receipts (not evidence): ${anvilGas.map((x) => `\`${x}\``).join(", ")}.`);
s.push("");
s.push("## B3: MIP-8 storage layout effect");
s.push("_**Cut** (owner decision D12, 5 Oct): B3 needs the same MM cycle on a level-array vs a mapping-layout OrderBook, measured on testnet (BENCHMARKS_PLAN B3). The mapping-layout variant would be a bench-only contract to write, deploy and fund before the 8 Oct freeze, for a claim the Foundry B1 numbers and MIP-8 page pricing already explain. Not run; no number is claimed._");
s.push("");
s.push("## B4: multi-market parallel load");
if (loadFiles.length === 0) {
  s.push("_Not run on testnet: **BLOCKED #5 paid RPC** (HUMAN_CHECKLIST #5). Decision D12 approved a reduced B4 on 10143 within ≤ 2.0 testnet MON on a non-public RPC; on 5 Oct the configured testnet endpoint turned out to be a **free tier** (`eth_getLogs` ≤ 10 blocks, HTTP 429 under a short scan), and the keys hold ≈ 1.25 testnet MON after the aborted B1/B2 rerun (`bench/out/partial_gas_onchain_10143_2026-10-05.csv`, not used here). Smallest meaningful B4 (`DRY_RUN=1`, 2 wallets × 15 txs × K = 1, 2) projects ≈ 1.38 MON + 12 unpriced setup txs; full B4 (4 × 60) ≈ 5.2 MON. `bench/load.ts` is ready (K markets, pipelined nonces; outputs record the RPC tier, never the URL)._" + (anvilLoad.length ? ` Local-only runs: ${anvilLoad.map((x) => `\`${x}\``).join(", ")}.` : ""));
} else {
  for (const f of loadFiles) {
    const j = JSON.parse(readFileSync(`${OUT}${f}`, "utf8")) as { chainId: number; results: Array<Record<string, number>> };
    s.push(`Source \`bench/out/${f}\` (chain ${j.chainId}).`);
    s.push("| K markets | sent | included | blocks | tx/block | landed p50 (ms) | p95 (ms) |\n|---|---|---|---|---|---|---|");
    for (const r of j.results) s.push(`| ${r.markets} | ${r.sent} | ${r.included} | ${r.blocks} | ${r.txPerBlock} | ${r.latencyMsP50} | ${r.latencyMsP95} |`);
  }
}
s.push("");
s.push("## B5 funding granularity · B8 UX latency · B9 vault economics");
s.push("_Pending: B5 and B9 need indexer history (live Envio pending Docker); B8 needs the login decision + app instrumentation._");
s.push("");
s.push("## B6: √τ margin chart");
if (tau) {
  s.push("![√τ chart](../../bench/out/sqrt_tau.png)");
  s.push("");
  s.push("| design | τ (s) | z·σ·√τ at σ = 100% (%) | implied max leverage |\n|---|---|---|---|");
  for (const r of tau) s.push(`| ${r.design} | ${r.tau_s} | ${r.mmr_pct_sigma100} | ${Number(r.max_leverage_sigma100).toLocaleString("en-US")}x |`);
  s.push("");
  s.push("Honesty caveat (MATH_SPEC §3.4): the hourly / 8 h rows model designs whose risk state refreshes only at that interval; continuous-liquidation venues have τ = keeper latency. The claim is that funding, mark and liquidation eligibility all update every block here.");
} else s.push("_Run `python3 bench/sqrt_tau.py`._");
s.push("");
s.push("## B7: liquidation latency (realized)");
if (b7) {
  s.push("Source `bench/out/b7_liquidation_latency.csv` (every row has its blocks, tx, RPC and bots commit).");
  s.push("");
  s.push(renderB7(b7));
  s.push("");
  s.push("Testnet misses the ≤ 3-block target. It ran on the free public RPC, where the keeper's estimate + send + receipt path took ≈ 3.2 s (8 blocks of 400 ms); the target assumes a keeper on its own paid RPC. Locally the same keeper liquidates 1 block after eligibility.");
} else s.push("_No B7 data._");
s.push("");
mkdirSync(`${HERE}../docs/outputs`, { recursive: true });
writeFileSync(DOC, `${s.join("\n")}\n`);
console.log(`wrote ${DOC}`);
